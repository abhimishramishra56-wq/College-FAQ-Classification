# College FAQ Classification System

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB

# Sample training questions
questions = [
    "When is my exam?",
    "What is the exam date?",
    "When will exams start?",
    "What is the college fee?",
    "How can I pay fees?",
    "What is the tuition fee?",
    "When will results come?",
    "How can I check my result?",
    "Where is my result?",
    "What is the class timetable?",
    "When does the class start?",
    "What is today's schedule?",
    "How can I apply for admission?",
    "What are admission requirements?",
    "When does admission start?"
]

categories = [
    "Exams", "Exams", "Exams",
    "Fees", "Fees", "Fees",
    "Results", "Results", "Results",
    "Timetable", "Timetable", "Timetable",
    "Admissions", "Admissions", "Admissions"
]

# Convert text into numerical features
vectorizer = TfidfVectorizer()
X = vectorizer.fit_transform(questions)

# Train AI model
model = MultinomialNB()
model.fit(X, categories)

# Test the model
new_question = ["When is my exam?"]
new_data = vectorizer.transform(new_question)

prediction = model.predict(new_data)

print("Student Question:", new_question[0])
print("Predicted Category:", prediction[0])

test_questions = [
    "When will my exam start?",
    "How can I pay college fees?",
    "When will my result be declared?",
    "What is my class timetable?",
    "How can I apply for admission?"
]

for question in test_questions:
    data = vectorizer.transform([question])
    result = model.predict(data)
    print("Question:", question)
    print("Category:", result[0])
    print("--------------------")